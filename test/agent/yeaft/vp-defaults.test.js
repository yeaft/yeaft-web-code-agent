import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { DEFAULT_VPS } from '../../../agent/yeaft/vp/seed-defaults.js';
import { topUpDefaultVps } from '../../../agent/yeaft/vp/seed-topup.js';
import { buildRoleMd } from '../../../agent/yeaft/vp/vp-crud.js';

// Restrict this historical migration to the five stock owners.
const stockIds = ['omni', 'software-omni', 'writing-omni', 'short-video-omni', 'quant-omni'];
const PRIMARY_VPS = DEFAULT_VPS.filter(vp => stockIds.includes(vp.vpId));

// Exact bilingual bodies from role.md files generated by v1.0.713 (unchanged through v1.0.715).
const v713Souls = JSON.parse(readFileSync(new URL('./fixtures/scene-vp-souls-1.0.713.json', import.meta.url), 'utf8'));
// Exact bilingual bodies from role.md files generated by v1.0.716 (unchanged through v1.0.718).
const v716Souls = JSON.parse(readFileSync(new URL('./fixtures/scene-vp-souls-1.0.716.json', import.meta.url), 'utf8'));
// Exact bilingual bodies from role.md files generated by v1.0.719 (unchanged through v1.0.724).
const v719Souls = JSON.parse(readFileSync(new URL('./fixtures/scene-vp-souls-1.0.719.json', import.meta.url), 'utf8'));

let libDir;
const rolePath = vp => join(libDir, vp.vpId, 'role.md');
const readRole = vp => readFileSync(rolePath(vp), 'utf8');
function writeRole(vp, source) {
  mkdirSync(join(libDir, vp.vpId), { recursive: true });
  writeFileSync(rolePath(vp), source, 'utf8');
}

beforeEach(() => { libDir = mkdtempSync(join(tmpdir(), 'yeaft-vp-defaults-')); });
afterEach(() => { rmSync(libDir, { recursive: true, force: true }); });

describe('stock VP scenario defaults', () => {
  it('upgrades the five v1.0.713, v1.0.716 and v1.0.719 souls only for their exact contents and owner', () => {
    const ids = PRIMARY_VPS.map(vp => vp.vpId);
    for (const souls of [v713Souls, v716Souls, v719Souls]) {
      expect(Object.keys(souls).sort()).toEqual([...ids].sort());
      const sources = new Map();
      for (const kind of ['other-owner', 'one-character-edit', 'official']) {
        for (const [i, vp] of PRIMARY_VPS.entries()) {
          const body = kind === 'other-owner' ? souls[ids[(i + 1) % ids.length]] : souls[vp.vpId];
          const source = buildRoleMd({ ...vp, displayName: `My ${vp.vpId}`,
            persona: kind === 'one-character-edit' ? body.replace('。', '！') : body });
          writeRole(vp, source);
          sources.set(vp.vpId, source);
        }
        const result = topUpDefaultVps(libDir);
        expect(result.errors).toEqual([]);
        expect(result.personaBackfilled.sort()).toEqual(kind === 'official' ? [...ids].sort() : []);
        for (const vp of PRIMARY_VPS) {
          const source = sources.get(vp.vpId);
          expect(readRole(vp)).toBe(kind === 'official' ? source.replace(souls[vp.vpId], () => vp.persona.trim()) : source);
        }
      }
    }
  });

});
